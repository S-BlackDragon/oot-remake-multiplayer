"""Writes lichii/hook/coop_hud_font.h: the in-game HUD's bitmap font.

ProggyClean (Tristan Grimmer, MIT, see THIRD_PARTY_NOTICES.md) is a pixel font:
at 16 px its glyphs land on whole pixels, 7 wide and 13 tall. Each glyph is
rasterised without smoothing and stored as 13 rows of 7 bits (bit 6 is the
left column). Codepoints 32-126 and 160-255 (Latin-1: accented letters, n
with tilde); the rest is empty and drawn as '?'.

  python tools/hud_font/make_font.py <ProggyClean.ttf>

The font file is not in this repo: Dear ImGui ships it in misc/fonts/.
"""
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

W, H, SIZE = 7, 13, 16
FIRST, LAST = 32, 255


def glyph(font, ch):
    im = Image.new("L", (W + 4, H + 4), 0)
    d = ImageDraw.Draw(im)
    d.fontmode = "1"
    d.text((0, 0), ch, font=font, fill=255)
    rows = []
    for y in range(H):
        bits = 0
        for x in range(W):
            if im.getpixel((x, y)) > 127:
                bits |= 1 << (W - 1 - x)
        rows.append(bits)
    # Nothing may be cut off: columns W.. and rows H.. stay empty.
    for y in range(H + 4):
        for x in range(W, W + 4):
            assert im.getpixel((x, y)) <= 127, (ch, x, y)
    for y in range(H, H + 4):
        for x in range(W + 4):
            assert im.getpixel((x, y)) <= 127, (ch, x, y)
    return rows


def main() -> int:
    font = ImageFont.truetype(sys.argv[1], SIZE)
    assert font.getlength("M") == W
    missing = glyph(font, "\u0378")  # unassigned: the font's .notdef box
    table = []
    for cp in range(FIRST, LAST + 1):
        rows = [0] * H
        if 32 <= cp <= 126 or cp >= 160:
            g = glyph(font, chr(cp))
            if g != missing or cp == 32:
                rows = g
        table.append(rows)
    out = Path(__file__).resolve().parents[2] / "lichii/hook/coop_hud_font.h"
    lines = [
        "// SPDX-License-Identifier: MIT",
        "// Generated by tools/hud_font/make_font.py: do not edit.",
        "//",
        "// ProggyClean, Copyright (c) 2004, 2005 Tristan Grimmer, MIT License",
        "// (THIRD_PARTY_NOTICES.md), as a 7x13 bitmap: codepoints 32 to 255, 13 rows",
        "// each, bit 6 the left column. An all-zero glyph past the space is not in the",
        "// font (127-159, and any the font lacks).",
        "#pragma once",
        "",
        "#include <array>",
        "#include <cstdint>",
        "",
        "namespace CoopHudFont {",
        "",
        f"inline constexpr int kWidth = {W};",
        f"inline constexpr int kHeight = {H};",
        f"inline constexpr char32_t kFirst = {FIRST};",
        f"inline constexpr char32_t kLast = {LAST};",
        "",
        f"inline constexpr std::array<std::array<std::uint8_t, {H}>, {LAST - FIRST + 1}> kGlyphs{{{{",
    ]
    for cp, rows in zip(range(FIRST, LAST + 1), table):
        lines.append("    {{" + ", ".join(f"0x{r:02x}" for r in rows) + f"}}}},  // {cp}")
    lines += ["}};", "", "} // namespace CoopHudFont", ""]
    out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    present = sum(1 for cp, r in zip(range(FIRST, LAST + 1), table) if any(r))
    print(f"{out}: {present} glyphs drawn")
    return 0


if __name__ == "__main__":
    sys.exit(main())
